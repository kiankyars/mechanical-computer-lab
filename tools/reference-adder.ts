// Generator for machines/reference-adder.machine.json: the project's reference
// two-bit adder (whiffletree sum bar + clutch drive + clocked code-bar decoder).
//
//   npx tsx tools/reference-adder.ts          # rewrite the machine file
//   P='{"G":1.1}' OUT=/tmp/x.json npx tsx tools/reference-adder.ts
//
// Every coordinate and joint anchor is derived from the named parameters below,
// so joints are exactly consistent at construction. The output is plain
// machine JSON; the simulator never runs this code.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

type V = [number, number];
type Json = Record<string, unknown>;
const r9 = (x: number) => Math.round(x * 1e9) / 1e9;
const v = (x: number, y: number): V => [r9(x), r9(y)];
const sub = (a: V, b: V): V => v(a[0] - b[0], a[1] - b[1]);

const DESCRIPTION =
  "Reference two-bit adder (feasibility witness), computed by the crank. (1) Sum: an offset slider-crank moves a drive carriage left; through a preloaded clutch spring it carries the sum bar, whose whiffletree (rockers A and B, averaged by rocker C) ends in four ball knobs that stop on the input blocks' right faces. Arms 2:1 weight bit 1 twice bit 0 and C averages the two words, so the sum bar rests at x = X0 + (a+b)/6: the carry is this addition of displacements. After the knobs land the clutch compresses so the crank keeps turning; a dashpot paces the stroke and damped, counterweighted rockers land square. (2) Code: an inclined ideal slot makes the code bar right of the outputs drop as far as the sum bar travelled, putting one of seven levels in front of each output's nub; each level has a tooth (that sum bit is 0) or a gap (1). (3) Probe: near the carriage's dead centre a roller pin on the crank enters a curved channel on the probe slider and drives it 0.95 right; springs on the slider push each nub toward the code bar. A tooth stops it at 0.10 (reads 0); a gap lets it run to 0.85 (reads 1). The channel ends in a dwell arc and the crank stops just past dead centre, so nothing back-drives once the torque is removed. (4) Reset: the reverse stroke pulls the slider and, through lost-motion links, the outputs back, then hooks the sum bar home; a fixed comb squares the rockers. Energy: the crank does all the motion work (about 8 J per operation); the 3.3 J of initial spring energy is mostly the clutch preload, held against a stop. Generated by tools/reference-adder.ts.";

export const DEFAULTS = {
  // ---- input sensing whiffletree ----
  knobR: 0.12,
  clear: 0.15,
  barW: 0.02,
  cOffset: 1.5,
  tiltLim: 0.55,
  balance: true,
  rockDamp: 0.5,
  cDamp: 0.2,
  rockK: 1.0,
  cK: 0.5,
  sY: -0.5,
  sHalf: 0.01,
  cBar: 0.01,
  rodW: 0.03,
  damperC: 1.8,
  sMin: -2.0,
  // ---- drive: offset slider-crank -> carriage D on the sum bar tail -> preloaded clutch spring ----
  rc: 0.8,
  rod: 3.0,
  e: 2.0, // slider line height above the crank centre
  alpha0: 0.2,
  eps: 0.6, // stop this far past dead centre (toggle)
  clutchK: 0.3,
  clutchPre: 1.3, // preload force
  clutchL: 2.6, // anchor distance
  clutchC: 0.3,
  clutchMax: 2.2,
  // ---- probe pin + channel slider ----
  pinA: 2.5,
  pinR: 0.07,
  winEnd: 0.1,
  winLen: 0.8,
  psiMid: -0.6,
  H: 0.95,
  lead: 0.12,
  endDwell: 0.15,
  chStep: 0.12,
  chClr: 0.015,
  flare: 0.04,
  chThick: 0.05,
  // ---- probe slider return spring ----
  probeK: 0.1,
  probePre: 0.03,
  probeC: 0.03,
  // ---- outputs ----
  outK: 0.3,
  outC: 0.03,
  outL: 1.0,
  outPre: 0.3,
  tipX: 9.3,
  nubH: 0.03,
  faceGap: 0.1,
  gapDepth: 0.85,
  // ---- code bar ----
  G: 1.0,
  spineW: 0.02,
  strutH: 0.01,
  plateW: 0.01,
  extra: [0, 0, 0] as number[], // per-output level offset tweak (CB-local y)
};
export type Params = typeof DEFAULTS;

export function build(over: Partial<Params> = {}) {
  const p = { ...DEFAULTS, ...over };
  const bodies: Json[] = [];
  const joints: Json[] = [];
  const box = (hx: number, hy: number, off: V = [0, 0], angle = 0) => ({
    type: 'box',
    half: [r9(hx), r9(hy)],
    offset: v(off[0], off[1]),
    angle: r9(angle),
  });
  // box that falls back to a thin convex rectangle when a half-extent is below the 0.02 box minimum
  const tbox = (hx: number, hy: number, off: V = [0, 0]) =>
    hx >= 0.02 && hy >= 0.02
      ? box(hx, hy, off)
      : {
          type: 'convex',
          vertices: [
            v(off[0] - hx, off[1] - hy),
            v(off[0] + hx, off[1] - hy),
            v(off[0] + hx, off[1] + hy),
            v(off[0] - hx, off[1] + hy),
          ],
          offset: [0, 0],
          angle: 0,
        };
  const ball = (r: number, off: V = [0, 0]) => ({
    type: 'ball',
    radius: r9(r),
    offset: v(off[0], off[1]),
  });
  const poly = (pts: V[]) => ({
    type: 'convex',
    vertices: pts.map(([x, y]) => v(x, y)),
    offset: [0, 0],
    angle: 0,
  });
  const pos: Record<string, V> = {
    $ground: [0, 0],
    $crank: [0, -6],
    $s0: [8, 3],
    $s1: [8, 0],
    $s2: [8, -3],
  };
  const add = (
    id: string,
    label: string,
    at: V,
    shapes: Json[],
    type = 'dynamic',
  ) => {
    pos[id] = v(at[0], at[1]);
    bodies.push({ id, label, type, position: pos[id], angle: 0, shapes });
  };
  const rev = (id: string, a: string, b: string, w: V, limits?: V) => {
    const j: Json = {
      id,
      type: 'revolute',
      a,
      b,
      anchorA: sub(w, pos[a]),
      anchorB: sub(w, pos[b]),
    };
    if (limits) j.limits = limits;
    joints.push(j);
  };
  const weld = (id: string, a: string, b: string, w: V) =>
    joints.push({
      id,
      type: 'fixed',
      a,
      b,
      anchorA: sub(w, pos[a]),
      anchorB: sub(w, pos[b]),
    });
  const slide = (
    id: string,
    a: string,
    b: string,
    w: V,
    axis: V,
    limits: V,
  ) => {
    const n = Math.hypot(axis[0], axis[1]);
    joints.push({
      id,
      type: 'prismatic',
      a,
      b,
      anchorA: sub(w, pos[a]),
      anchorB: sub(w, pos[b]),
      axis: v(axis[0] / n, axis[1] / n),
      limits: v(limits[0], limits[1]),
    });
  };
  const spring = (
    id: string,
    a: string,
    b: string,
    wa: V,
    wb: V,
    k: number,
    c: number,
    rest?: number,
  ) => {
    const d = Math.hypot(wa[0] - wb[0], wa[1] - wb[1]);
    joints.push({
      id,
      type: 'spring',
      a,
      b,
      anchorA: sub(wa, pos[a]),
      anchorB: sub(wb, pos[b]),
      restLength: r9(rest ?? d),
      stiffness: r9(k),
      damping: r9(c),
    });
  };
  let springE = 0;
  const addE = (k: number, dx: number) => (springE += 0.5 * k * dx * dx);

  // ---------------- whiffletree ----------------
  const face1 = -7.82;
  const xk = face1 + p.knobR + p.clear;
  const PA: V = [xk, 2.5],
    PB: V = [xk, -3.5],
    PC: V = [xk, p.sY];
  // balanced rocker: a counterweight below the pivot puts the centre of mass on the pin, so the rocker does
  // not swing while the tree accelerates and both knobs land square
  let yCw = 2;
  if (p.balance) {
    const mk = Math.PI * p.knobR * p.knobR;
    for (let it = 0; it < 60; it++) {
      const ab = 2 * p.barW * (2 + yCw);
      yCw = ((ab * (2 - yCw)) / 2 + mk) / mk;
    }
  }
  const rocker = (id: string, label: string, P: V) =>
    add(
      id,
      label,
      P,
      p.balance
        ? [
            tbox(p.barW, (2 + yCw) / 2, [0, (2 - yCw) / 2]),
            ball(p.knobR, [0, 2]),
            ball(p.knobR, [0, -1]),
            ball(p.knobR, [0, -yCw]),
          ]
        : [
            tbox(p.barW, 1.5, [0, 0.5]),
            ball(p.knobR, [0, 2]),
            ball(p.knobR, [0, -1]),
          ],
    );
  rocker(
    'a-rocker',
    'A rocker: knobs feel a0 (arm 2) and a1 (arm 1), counterweighted; pin at (2*a1+a0)/3',
    PA,
  );
  rocker(
    'b-rocker',
    'B rocker: knobs feel b0 (arm 2) and b1 (arm 1), counterweighted; pin at (2*b1+b0)/3',
    PB,
  );
  const cH = (PA[1] - PB[1]) / 2;
  add(
    'c-rocker',
    'C rocker: averages the A and B pins, so its centre pin moves sum/6',
    PC,
    [
      tbox(p.cBar, cH, [p.cOffset, 0]),
      tbox(p.cOffset / 2, p.cBar, [p.cOffset / 2, cH]),
      tbox(p.cOffset / 2, p.cBar, [p.cOffset / 2, -cH]),
    ],
  );
  rev('a-pin', 'c-rocker', 'a-rocker', PA, [-p.tiltLim, p.tiltLim]);
  if (p.rockDamp > 0) {
    // rotary dampers (near-zero stiffness): kill rocker spin after the knobs land
    spring(
      'a-damper',
      'c-rocker',
      'a-rocker',
      [PA[0] + 1, PA[1] + 1.2],
      [PA[0], PA[1] + 1.2],
      p.rockK,
      p.rockDamp,
    );
    spring(
      'b-damper',
      'c-rocker',
      'b-rocker',
      [PB[0] + 1, PB[1] + 1.2],
      [PB[0], PB[1] + 1.2],
      p.rockK,
      p.rockDamp,
    );
  }
  rev('b-pin', 'c-rocker', 'b-rocker', PB, [-p.tiltLim, p.tiltLim]);
  {
    const x0 = xk + p.barW,
      hw = 0.12;
    const combY = [PA[1] + 1.35, PA[1] - 0.55, PB[1] + 1.55, PB[1] - 0.55];
    add(
      'reset-comb',
      'Reset comb: squares the A and B rockers when the reverse stroke pulls the tree home',
      [x0 + hw, 0],
      combY.map((y) => box(hw, 0.14, [0, y])),
      'fixed',
    );
  }

  // ---------------- drive geometry ----------------
  const C0: V = [0, -6];
  const yD = C0[1] + p.e;
  const xD = (a: number) =>
    p.rc * Math.cos(a) -
    Math.sqrt(p.rod * p.rod - (p.rc * Math.sin(a) - p.e) ** 2);
  const alphaDC =
    Math.PI - Math.atan2(p.e, Math.sqrt((p.rod + p.rc) ** 2 - p.e * p.e));
  const alphaEnd = alphaDC + p.eps;
  const thetaMax = alphaEnd - p.alpha0;
  const X0: V = [xD(p.alpha0), yD];
  const stroke = X0[0] - xD(alphaDC);
  const T0: V = [
    C0[0] + p.rc * Math.cos(p.alpha0),
    C0[1] + p.rc * Math.sin(p.alpha0),
  ];

  // ---------------- sum bar S (with tail down to the carriage) ----------------
  add(
    'sum-bar',
    `Sum bar: carried left until all four knobs rest on the inputs; comes to rest at x = ${r9(-8.82 + p.knobR)} + sum/6`,
    PC,
    [
      tbox((X0[0] - xk) / 2, p.sHalf, [(X0[0] - xk) / 2, 0]),
      tbox(p.sHalf, (p.sY - yD) / 2, [X0[0] - xk, (yD - p.sY) / 2 + 0]),
    ],
  );
  rev('c-pin', 'sum-bar', 'c-rocker', PC);
  if (p.cDamp > 0)
    spring(
      'c-damper',
      'sum-bar',
      'c-rocker',
      [PC[0] + 1, PC[1] + 2.5],
      [PC[0], PC[1] + 2.5],
      p.cK,
      p.cDamp,
    );
  slide('sum-guide', '$ground', 'sum-bar', PC, [1, 0], [p.sMin, 0.05]);
  add(
    'drive-carriage',
    'Drive carriage: rides the sum-bar tail; pushes it via the clutch spring, hooks it home on reset',
    X0,
    [box(0.14, 0.1)],
  );
  slide(
    'clutch-slide',
    'sum-bar',
    'drive-carriage',
    X0,
    [1, 0],
    [-p.clutchMax, 0],
  );
  {
    const d0 = p.clutchPre / p.clutchK;
    spring(
      'clutch-spring',
      'drive-carriage',
      'sum-bar',
      X0,
      [X0[0] - p.clutchL, yD],
      p.clutchK,
      p.clutchC,
      p.clutchL + d0,
    );
    addE(p.clutchK, d0);
  }

  if (p.damperC > 0)
    spring(
      'drive-damper',
      '$ground',
      'drive-carriage',
      [X0[0] + 2, yD],
      X0,
      0.1,
      p.damperC,
    );
  // ---------------- crank arm + probe pin ----------------
  const thC1 = thetaMax - p.winEnd,
    thC0 = thC1 - p.winLen,
    thMid = (thC0 + thC1) / 2;
  const psi0 = p.psiMid - thMid; // world angle of the probe pin at theta = 0
  const pinAt = (th: number): V => [
    C0[0] + p.pinA * Math.cos(psi0 + th),
    C0[1] + p.pinA * Math.sin(psi0 + th),
  ];
  const cyc = (u: number) =>
    u <= 0 ? 0 : u >= 1 ? 1 : u - Math.sin(2 * Math.PI * u) / (2 * Math.PI);
  const xs = (th: number) => p.H * cyc((th - thC0) / p.winLen); // probe slider displacement vs crank angle
  add(
    'crank-arm',
    'Crank arm (welded to the crank): carries the drive pin and the probe pin',
    C0,
    [
      box(
        p.rc / 2 + 0.06,
        0.06,
        [(p.rc / 2) * Math.cos(p.alpha0), (p.rc / 2) * Math.sin(p.alpha0)],
        p.alpha0,
      ),
    ],
  );
  weld('crank-weld', '$crank', 'crank-arm', C0);
  joints.push({
    id: 'crank-stop',
    type: 'revolute',
    a: '$ground',
    b: '$crank',
    anchorA: C0,
    anchorB: [0, 0],
    limits: [-0.05, r9(thetaMax)],
  });
  const RM: V = [(T0[0] + X0[0]) / 2, (T0[1] + X0[1]) / 2];
  const beta = Math.atan2(T0[1] - X0[1], T0[0] - X0[0]);
  add('drive-rod', 'Connecting rod: crank pin -> drive carriage', RM, [
    box(p.rod / 2 - 0.15, p.rodW, [0, 0], beta),
  ]);
  rev('rod-crank', 'crank-arm', 'drive-rod', T0);
  rev('rod-carriage', 'drive-rod', 'drive-carriage', X0);
  const PIN0 = pinAt(0);
  add(
    'probe-pin',
    'Probe pin: roller on the crank that runs in the probe slider channel near the end of the stroke',
    PIN0,
    [ball(p.pinR)],
  );
  rev('probe-pin-axle', 'crank-arm', 'probe-pin', PIN0);

  // ---------------- probe slider with channel ----------------
  // channel centreline (slider frame at rest == world): c(th) = pin(th) - (xs(th), 0)
  const SL: V = v(C0[0] + p.pinA + 0.4, C0[1]); // slider body origin
  const thA = thC0 - p.lead,
    thZ = thetaMax + p.endDwell;
  const nSeg = Math.max(6, Math.ceil((thZ - thA) / p.chStep));
  const cl: V[] = [];
  for (let i = 0; i <= nSeg; i++) {
    const th = thA + ((thZ - thA) * i) / nSeg;
    const q = pinAt(th);
    cl.push([q[0] - xs(th) - SL[0], q[1] - SL[1]]);
  }
  const nrm = cl.map((_, i) => {
    const a0 = cl[Math.max(0, i - 1)],
      a1 = cl[Math.min(cl.length - 1, i + 1)];
    const dx = a1[0] - a0[0],
      dy = a1[1] - a0[1],
      L = Math.hypot(dx, dy);
    return [-dy / L, dx / L] as V; // left normal
  });
  const clr = (i: number) => p.chClr + Math.max(0, 1 - i / 2) * p.flare; // flared mouth
  const convexOK = (pts: V[]) => {
    for (let k = 0; k < pts.length; k++) {
      const A = pts[k],
        B = pts[(k + 1) % pts.length],
        C = pts[(k + 2) % pts.length];
      if ((B[0] - A[0]) * (C[1] - B[1]) - (B[1] - A[1]) * (C[0] - B[0]) <= 3e-4)
        return false;
    }
    return true;
  };
  const chPieces: Json[] = [];
  for (const side of [1, -1]) {
    const inner = cl.map(
      (c, i) =>
        [
          c[0] + side * nrm[i][0] * (p.pinR + clr(i)),
          c[1] + side * nrm[i][1] * (p.pinR + clr(i)),
        ] as V,
    );
    const outer = cl.map(
      (c, i) =>
        [
          c[0] + side * nrm[i][0] * (p.pinR + clr(i) + p.chThick),
          c[1] + side * nrm[i][1] * (p.pinR + clr(i) + p.chThick),
        ] as V,
    );
    let i = 0;
    while (i < cl.length - 1) {
      let j = i + 1,
        best: V[] | null = null;
      for (; j < cl.length; j++) {
        let pts: V[] = [
          ...inner.slice(i, j + 1),
          ...outer.slice(i, j + 1).reverse(),
        ];
        if (side < 0) pts = pts.reverse();
        if (pts.length > 16 || !convexOK(pts)) break;
        best = pts;
      }
      if (!best) throw new Error('channel piece not convex at ' + i);
      chPieces.push(poly(best));
      i = j - 1;
    }
  }
  const chunks: Json[][] = [];
  for (let k = 0; k < chPieces.length; k += 8)
    chunks.push(chPieces.slice(k, k + 8));
  add(
    'probe-slider',
    'Probe slider: channel takes the crank pin after the sum settles, pushes the output springs, locks',
    SL,
    chunks[0],
  );
  slide(
    'probe-guide',
    '$ground',
    'probe-slider',
    SL,
    [1, 0],
    [-0.05, p.H + 0.2],
  );
  chunks.slice(1).forEach((ch, k) => {
    add(
      `probe-channel-${k + 1}`,
      'Probe slider channel section (welded to the probe slider)',
      SL,
      ch,
    );
    // chain the welds so every pair of touching channel sections is directly joined (no self-contact)
    weld(
      `probe-channel-${k + 1}-weld`,
      k === 0 ? 'probe-slider' : `probe-channel-${k}`,
      `probe-channel-${k + 1}`,
      SL,
    );
  });
  {
    const L = 1.5,
      d0 = p.probePre / p.probeK;
    spring(
      'probe-return',
      '$ground',
      'probe-slider',
      [SL[0] - L, SL[1]],
      SL,
      p.probeK,
      p.probeC,
      L - d0,
    );
    addE(p.probeK, d0);
  }
  const probeId = 'probe-slider';

  // ---------------- outputs: nub fingers, lost-motion link to probe rod, push springs ----------------
  const outs = [
    { id: '$s0', name: 's0', y: 3, bits: [0, 1, 0, 1, 0, 1, 0] },
    { id: '$s1', name: 's1', y: 0, bits: [0, 0, 1, 1, 0, 0, 1] },
    { id: '$s2', name: 's2', y: -3, bits: [0, 0, 0, 0, 1, 1, 1] },
  ];
  for (const o of outs) {
    const fx0 = 8.0,
      fx1 = p.tipX;
    const FC: V = [(fx0 + fx1) / 2, o.y];
    add(
      `${o.name}-nub`,
      `${o.name.toUpperCase()} nub: welded to the output flag; stopped by a tooth (0) or runs into a gap to the spine (1)`,
      FC,
      [box((fx1 - fx0) / 2, p.nubH)],
    );
    weld(`${o.name}-nub-weld`, o.id, `${o.name}-nub`, [8, o.y]);
    slide(`${o.name}-link`, probeId, o.id, [8, o.y], [1, 0], [-1.35, 0]);
    spring(
      `${o.name}-push`,
      probeId,
      o.id,
      [8 - p.outL, o.y],
      [8, o.y],
      p.outK,
      p.outC,
      p.outL + p.outPre / p.outK,
    );
    addE(p.outK, p.outPre / p.outK);
  }

  // ---------------- code bar ----------------
  const xFace = p.tipX + p.faceGap;
  const xsp = p.tipX + p.gapDepth;
  const pitchY = p.G / 6;
  const CB: V = [xsp, 0];
  const cbShapes: Json[] = [];
  const plates: Json[] = [];
  const teeth: Json[] = [];
  let yLo = 9,
    yHi = -9;
  outs.forEach((o, i) => {
    const yn = (k: number) =>
      o.y + p.G * (1 + p.clear - k / 6) + (p.extra[i] ?? 0); // CB-local y of nub at level k
    for (let k1 = 0; k1 <= 6; k1++) {
      if (o.bits[k1] || (k1 > 0 && !o.bits[k1 - 1])) continue;
      let k2 = k1;
      while (k2 + 1 <= 6 && !o.bits[k2 + 1]) k2++;
      const top = yn(k1) + pitchY / 2 + (k1 === 0 ? pitchY : 0);
      const bot = yn(k2) - pitchY / 2 - (k2 === 6 ? pitchY : 0);
      const mid = (top + bot) / 2;
      cbShapes.push(
        tbox((xsp - xFace) / 2, p.strutH, [(xFace - xsp) / 2, mid]),
      ); // strut back to the spine
      plates.push(
        tbox(p.plateW, (top - bot) / 2, [xFace + p.plateW - xsp, mid]),
      ); // blocking face
      teeth.push({ out: o.name, k1, k2, y: [r9(bot), r9(top)] });
      yLo = Math.min(yLo, bot);
      yHi = Math.max(yHi, top);
    }
  });
  // spine spans every nub position (levels -1..7) so a free nub always stops on it
  outs.forEach((o, i) => {
    const yn = (k: number) =>
      o.y + p.G * (1 + p.clear - k / 6) + (p.extra[i] ?? 0);
    yLo = Math.min(yLo, yn(7) - 0.05);
    yHi = Math.max(yHi, yn(-1) + 0.05);
  });
  yLo -= 0.05;
  yHi += 0.05;
  cbShapes.unshift(
    tbox(p.spineW / 2, (yHi - yLo) / 2, [p.spineW / 2, (yHi + yLo) / 2]),
  );
  add(
    'code-bar',
    'Code bar: drops with the sum bar via an inclined slot; a tooth stands wherever a sum bit is 0',
    CB,
    cbShapes,
  );
  if (plates.length) {
    add(
      'code-faces',
      'Code bar tooth faces: stop an output nub at 0.10 where its sum bit is 0',
      CB,
      plates,
    );
    weld('code-faces-weld', 'code-bar', 'code-faces', CB);
  }
  // non-redundant guidance: a shoe slides on a vertical ground rail, the code bar pivots on the shoe,
  // and the inclined slot to the sum bar fixes both its height and its angle.
  const SH: V = v(CB[0] + 0.6, CB[1]);
  add(
    'code-shoe',
    'Code bar shoe: rides a vertical rail; the code bar hangs on it by a pin',
    SH,
    [box(0.06, 0.15)],
  );
  slide('code-guide', '$ground', 'code-shoe', SH, [0, 1], [-p.G * 1.7, 0.05]);
  rev('code-shoe-pin', 'code-shoe', 'code-bar', SH);
  const nS = Math.hypot(1, p.G);
  slide(
    'code-slot',
    'sum-bar',
    'code-bar',
    [1.5, 0],
    [1, -p.G],
    [-0.05 * nS, 1.7 * nS],
  );

  // rod clearance to the crank disk (radius 0.5) along the stroke
  let minClear = 9;
  for (let a = p.alpha0; a <= alphaEnd; a += 0.005) {
    const px = p.rc * Math.cos(a),
      py = p.rc * Math.sin(a);
    const dx = xD(a) - px,
      dy = p.e - py,
      L = Math.hypot(dx, dy);
    let t = (-px * dx - py * dy) / (L * L);
    t = Math.max(0.15 / L, Math.min(1 - 0.15 / L, t));
    minClear = Math.min(
      minClear,
      Math.hypot(px + t * dx, py + t * dy) - 0.5 - 0.05,
    );
  }
  const machine = {
    version: 1,
    name: 'Reference adder · clocked code bar',
    description: DESCRIPTION.replace('X0', String(r9(-8.82 + p.knobR))),
    bodies,
    joints,
    carryCandidates: ['c-rocker', 'code-bar', 'code-faces'],
  };
  return {
    machine,
    info: {
      xk,
      X0,
      T0,
      yD,
      alphaDC: r9(alphaDC),
      thetaMax: r9(thetaMax),
      thC0: r9(thC0),
      thC1: r9(thC1),
      stroke: r9(stroke),
      minClear: r9(minClear),
      springE: r9(springE),
      teeth,
    },
  };
}

/** One body or joint per line: diffable without a 2,000-line file. */
export function serialize(machine: Json): string {
  const lines = (items: unknown) =>
    (items as unknown[])
      .map((item) => '    ' + JSON.stringify(item))
      .join(',\n');
  return [
    '{',
    `  "version": ${JSON.stringify(machine.version)},`,
    `  "name": ${JSON.stringify(machine.name)},`,
    `  "description": ${JSON.stringify(machine.description)},`,
    `  "bodies": [\n${lines(machine.bodies)}\n  ],`,
    `  "joints": [\n${lines(machine.joints)}\n  ],`,
    `  "carryCandidates": ${JSON.stringify(machine.carryCandidates)}`,
    '}',
    '',
  ].join('\n');
}

